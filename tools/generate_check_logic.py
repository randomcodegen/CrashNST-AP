"""generate level titles and valid requirement IDs from the APWorld"""

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "CrashNST-APWorld/worlds/crash_nst"))
from data import LEVELS, ITEMS, checks, check_requirements, CRATE_GEM_REQUIREMENTS, SECRET_CRATE_EVENTS


def header():
    lines = ["// Generated by tools/generate_check_logic.py. Do not edit by hand!"]
    for level in LEVELS:
        events = [event for event, _, _ in checks(level)]
        if level.key.startswith("L"):
            events.append("box:")
            events.extend(
                event for key, event in CRATE_GEM_REQUIREMENTS if key == level.key
            )
            events.extend(event for key, event in sorted(SECRET_CRATE_EVENTS) if key == level.key)
        events = list(dict.fromkeys(events))
        rules = []
        for event in events:
            ids = ", ".join(
                str(ITEMS[name]) for name in check_requirements(level, event, (level,))
            )
            rules.append("{" + json.dumps(event) + ", {" + ids + "}}")
        lines.append(
            "    {"
            + json.dumps(level.key)
            + ", "
            + json.dumps(level.name)
            + ", {"
            + ", ".join(rules)
            + "}},"
        )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    output = ROOT / "CrashNST-AP-Client/client/check_logic_specs.inc"
    output.write_text(header(), encoding="utf-8")
    print(output)
